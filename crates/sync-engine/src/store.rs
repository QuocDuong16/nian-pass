const SCHEMA_VERSION: u32 = 2;
const MAX_METADATA_BYTES: u64 = 64 * 1024;
const BASE_METADATA: &str = "base.json";
const JOURNAL_METADATA: &str = "journal.json";

/// Collision-resistant random sync profile identity.
#[derive(Clone, Copy, Eq, PartialEq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct ProfileId(Uuid);

impl ProfileId {
    /// Generates a random UUID v4 profile identity.
    #[must_use]
    pub fn random() -> Self {
        Self(Uuid::new_v4())
    }

    /// Parses a UUID and rejects non-v4 identities.
    pub fn parse(value: &str) -> Result<Self, StoreError> {
        let value = Uuid::parse_str(value).map_err(|_| StoreError::InvalidMetadata)?;
        if value.get_version_num() != 4 {
            return Err(StoreError::InvalidMetadata);
        }
        Ok(Self(value))
    }

    /// Returns the canonical UUID string.
    #[must_use]
    pub fn to_canonical_string(self) -> String {
        self.0.hyphenated().to_string()
    }
}

/// Private stable identity binding a profile to one local source.
#[derive(Clone, Eq, PartialEq, Serialize, Deserialize)]
#[serde(transparent)]
pub struct SourceBinding(String);

impl SourceBinding {
    /// Accepts a canonical lowercase SHA-256 binding generated by an adapter.
    pub fn from_sha256(value: String) -> Result<Self, StoreError> {
        CiphertextDigest::parse(value.clone()).map_err(|_| StoreError::InvalidMetadata)?;
        Ok(Self(value))
    }

    /// Returns the private canonical binding for profile metadata.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Private stable identity binding persisted sync state to one remote target.
#[derive(Clone, Eq, PartialEq, Serialize, Deserialize)]
